import assert from 'node:assert/strict'
import {writeFile} from 'node:fs/promises'
import { createServer } from 'vite'
import { chromium } from '../node_modules/.qa/node_modules/playwright-core/index.mjs'

const executablePath = process.argv[2] ?? 'C:/Program Files/Google/Chrome/Application/chrome.exe'
const testPort = Number(process.env.AV_TEST_PORT ?? 4173)
const vite = await createServer({server:{host:'127.0.0.1',port:testPort,strictPort:true},optimizeDeps:{include:['react/jsx-dev-runtime']}})
await vite.listen()
let browser
try {
  browser = await chromium.launch({ executablePath })
  const context = await browser.newContext()
  const page = await context.newPage()
  const errors = []
  page.on('pageerror', error=>errors.push(error))
  await page.goto('http://127.0.0.1:'+testPort+'/')
  await page.getByRole('heading',{name:'忘年会 AVコントローラー'}).waitFor()
  await page.getByRole('button',{name:'音声を有効化',exact:true}).click()
  await page.getByText('● 音声 有効',{exact:true}).waitFor()
  const [popup] = await Promise.all([page.waitForEvent('popup'),page.getByRole('button',{name:'映像出力画面を開く'}).click()])
  await popup.getByRole('button',{name:'全画面にする'}).click()
  await popup.waitForFunction(()=>!!document.fullscreenElement)
  await page.getByRole('button',{name:'事前読み込み・本番モード開始'}).click()
  await page.getByText('本番モード · 5 件を準備済み',{exact:true}).waitFor()
  await context.setOffline(true)
  await page.getByText('● オフライン',{exact:true}).waitFor()
  await page.getByRole('button',{name:'開場BGMを本番出力'}).click()
  await page.getByText(/^開場BGM · 0:/).waitFor()
  await page.getByRole('button',{name:'ピンポンを本番出力'}).click()
  await page.getByRole('button',{name:'チャイムを本番出力'}).click()
  await page.getByRole('button',{name:'イベントタイトルを本番出力'}).click()
  await popup.locator('img').waitFor({state:'visible'})
  await page.getByRole('article').filter({hasText:'登場ジングル'}).getByRole('button',{name:'確認'}).click()
  assert.equal(await page.locator('dialog audio').evaluate(el=>el.muted && el.paused),true)
  assert.equal(await popup.locator('img').isVisible(),true)
  await page.getByRole('button',{name:'閉じる',exact:true}).click()
  await page.getByRole('button',{name:'全音声停止',exact:true}).click()
  await page.getByText('BGM 停止中',{exact:true}).waitFor()
  assert.equal(await popup.locator('img').isVisible(),true)
  await page.getByRole('button',{name:'黒画面',exact:true}).click()
  await popup.locator('img').waitFor({state:'hidden'})
  await popup.close()
  await page.getByRole('alert').getByText(/映像出力が切断/).waitFor()
  const [replacement] = await Promise.all([page.waitForEvent('popup'),page.getByRole('button',{name:'映像出力画面を開く'}).click()])
  await page.getByRole('button',{name:'イベントタイトルを本番出力'}).click()
  await replacement.locator('img').waitFor({state:'visible'})
  await page.getByRole('button',{name:'本番モードを終了'}).click()
  await page.getByText('準備モード',{exact:true}).waitFor()
  assert.deepEqual(await page.evaluate(()=>caches.keys()),[])
  await replacement.close()
  await context.setOffline(false)

  page.on('popup', async projector => {
    await projector.getByRole('button',{name:'全画面にする'}).click().catch(error=>errors.push(error))
  })
  await page.exposeFunction('setNetworkOffline',value=>context.setOffline(value))
  const result = await page.evaluate(async ()=>{
    const {Mixer} = await import('/src/mixer.ts')
    const {Output} = await import('/src/output.ts')
    const {makeDemo} = await import('/src/demo.ts')
    const {Assets, inspect, probe} = await import('/src/data.ts')
    const local = new Map()
    const [bgm,,effect,other] = makeDemo(local)
    let rejected=false
    try { await inspect(new File(['invalid'], 'invalid.png'),'image') } catch { rejected=true }
    if(!rejected)throw Error('Invalid PNG accepted')
    const mixer = new Mixer()
    await mixer.ctx.resume()
    const delay = ms => new Promise(resolve=>setTimeout(resolve,ms))
    const require = (condition, label) => {if(!condition)throw Error(label)}
    await mixer.play(bgm,async()=>local.get(bgm.storage_path))
    await Promise.all([mixer.preload(effect,local.get(effect.storage_path)),mixer.preload(other,local.get(other.storage_path))])
    await mixer.play(effect,async()=>local.get(effect.storage_path))
    await delay(130)
    require(Math.abs(mixer.duck.gain.value-0.4)<0.03,'Ducking attack')
    await mixer.play(other,async()=>local.get(other.storage_path))
    await delay(400)
    require(Math.abs(mixer.duck.gain.value-0.4)<0.03,'Ducking with overlap')
    for(let i=0;i<30 && mixer.duck.gain.value<=0.97;i++)await delay(100)
    require(mixer.duck.gain.value>0.97,'Ducking release')
    mixer.toggleBgm()
    require(mixer.isPaused,'BGM pause')
    mixer.toggleBgm()
    require(!mixer.isPaused && mixer.current?.id===bgm.id,'BGM resume')
    const canvas=document.createElement('canvas')
    canvas.width=160;canvas.height=90
    const draw=canvas.getContext('2d')
    draw.fillStyle='#36bea5'
    draw.fillRect(0,0,160,90)
    for(const type of ['image/png','image/jpeg','image/webp']) {
      const blob=await new Promise(resolve=>canvas.toBlob(resolve,type))
      const url=URL.createObjectURL(blob)
      const meta=await probe(url,'image',true)
      require(meta.blob?.type==='image/jpeg',type+' thumbnail')
      URL.revokeObjectURL(url)
    }
    const source=mixer.ctx.createMediaStreamDestination()
    const tone=mixer.ctx.createOscillator()
    tone.connect(source)
    tone.start()
    const animation=setInterval(()=>{draw.fillStyle=Math.random()>0.5?'#36bea5':'#b4466d';draw.fillRect(0,0,160,90)},40)
    const stream=new MediaStream([...canvas.captureStream(25).getVideoTracks(),...source.stream.getAudioTracks()])
    let m4aBytes
    if (MediaRecorder.isTypeSupported('audio/mp4;codecs=mp4a.40.2')) {
      const chunks=[]
      const recorder=new MediaRecorder(source.stream,{mimeType:'audio/mp4;codecs=mp4a.40.2'})
      recorder.ondataavailable=e=>chunks.push(e.data)
      const stopped=new Promise(resolve=>recorder.onstop=resolve)
      recorder.start()
      await delay(850)
      recorder.stop()
      await stopped
      const file=new File(chunks,'test.m4a',{type:'audio/mp4'})
      const {mime,ext}=await inspect(file,'effect')
      require(mime==='audio/mp4' && ext==='m4a','M4A validation')
      const u=URL.createObjectURL(file)
      const meta=await probe(u,'effect')
      const buffer=await mixer.preload({...effect,storage_path:'test-m4a'},u)
      require(meta.duration>0 && buffer.duration>0,'M4A metadata and decode')
      await mixer.play({...effect,storage_path:'test-m4a'},async()=>u)
      require(Array.from(mixer.voices).some(v=>v.media.storage_path==='test-m4a'),'M4A playback')
      URL.revokeObjectURL(u)
      m4aBytes=Array.from(new Uint8Array(await file.arrayBuffer()))
    }
    const formats = []
    try {
      for(const mimeType of ['video/webm','video/mp4']) {
        if(!MediaRecorder.isTypeSupported(mimeType))continue
        const chunks=[]
        const recorder=new MediaRecorder(stream,{mimeType})
        recorder.ondataavailable=e=>chunks.push(e.data)
        const stopped=new Promise(resolve=>recorder.onstop=resolve)
        recorder.start()
        await delay(780)
        recorder.stop()
        await stopped
        const blob=new Blob(chunks,{type:mimeType})
        const url=URL.createObjectURL(blob)
        const meta=await probe(url,'video',true)
        require(meta.blob?.size && meta.duration>0,'Video probe and thumbnail '+mimeType)
        const media={...bgm,media_type:'video',storage_path:mimeType,ducking_enabled:true,loop_enabled:true}
        const assets=new Assets()
        assets.local.set(media.storage_path,url)
        await assets.prepare([media],(m,u)=>probe(u,m.media_type),()=>{})
        await window.setNetworkOffline(true)
        const output=new Output(mixer,m=>assets.resolve(m),()=>undefined,()=>{})
        output.open()
        for(let i=0;i<50 && !output.win.document.fullscreenElement;i++)await delay(100)
        require(output.win.document.fullscreenElement,'Projector activated for video')
        await output.play(media)
        await delay(160)
        require(output.status==='再生中','Video played: '+output.error)
        require(mixer.duck.gain.value<0.6,'Video ducking')
        const meter=mixer.ctx.createAnalyser()
        mixer.videoGate.connect(meter)
        const samples=new Float32Array(meter.fftSize)
        await delay(160)
        meter.getFloatTimeDomainData(samples)
        require(samples.some(v=>Math.abs(v)>0.005),'Projected video delivers audio to the mixer')
        await output.transport('toggle')
        require(output.video.paused,'Video pause')
        await output.transport('restart')
        require(!output.video.paused,'Video restart')
        await delay(950)
        require(!output.video.paused && !output.video.ended,'Video loop')
        output.mute()
        await delay(80)
        meter.getFloatTimeDomainData(samples)
        require(!samples.some(v=>Math.abs(v)>0.005) && !output.video.paused,'Mute preserves video')
        await output.play({...media,loop_enabled:false,end_action:'standby'})
        await delay(1100)
        require(output.status==='停止中' && !output.media,'Video returns to standby')
        output.close()
        await window.setNetworkOffline(false)
        await assets.clear()
        URL.revokeObjectURL(url)
        formats.push(mimeType)
      }
    } finally {clearInterval(animation);tone.stop();await mixer.ctx.close()}
    return {formats,m4aBytes}
  })
  assert.ok(result.formats.includes('video/webm'))
  assert.ok(result.m4aBytes?.length,'AAC M4A recording and playback')
  if(process.env.AV_TEST_M4A_FILE) await writeFile(process.env.AV_TEST_M4A_FILE,Buffer.from(result.m4aBytes))
  assert.deepEqual(errors,[])
  console.log(browser.version(), 'passed: UI, fullscreen, offline, popup reopen, simultaneous effects, ducking, PNG/JPEG/WebP, '+result.formats.join(', ')+', AAC M4A')
} finally {await browser?.close();await vite.close()}
